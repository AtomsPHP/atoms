<?php

declare(strict_types=1);

namespace Atoms\Cli\Build;

use Atoms\Cli\Process\ProcessRunner;

/**
 * Stage 8 (full builds only): resolve atoms-composer.json in an isolated
 * directory and namespace-prefix the vendor tree with PHP-Scoper, so customer
 * dependencies cannot collide with the runtime's own or with another deploy.
 * `atoms/core` is never prefixed — it must unify with the runtime's copy.
 *
 * The command construction is unit-tested; the subprocess execution (network +
 * scoper binary) is not.
 */
final class ScoperStage
{
    public function __construct(private readonly ProcessRunner $runner)
    {
    }

    /**
     * The generated scoper.inc.php contents.
     */
    public static function config(string $prefix): string
    {
        $export = var_export($prefix, true);

        return <<<PHP
            <?php

            declare(strict_types=1);

            // Generated by `atoms build` — do not edit.
            return [
                'prefix' => {$export},
                'exclude-namespaces' => ['Atoms', 'Atoms\\\\*'],
                'exclude-files' => [],
                'expose-global-constants' => false,
                'expose-global-classes' => false,
                'expose-global-functions' => false,
            ];
            PHP;
    }

    /**
     * @return list<string>
     */
    public static function composerCommand(): array
    {
        return [
            'composer', 'install',
            '--no-dev', '--no-interaction', '--no-progress',
            '--ignore-platform-reqs', '--optimize-autoloader',
        ];
    }

    /**
     * @return list<string>
     */
    public static function scoperCommand(string $scoperBin, string $configPath, string $inputDir, string $outputDir): array
    {
        return [
            $scoperBin, 'add-prefix',
            $inputDir,
            '--config', $configPath,
            '--output-dir', $outputDir,
            '--force', '--no-interaction',
        ];
    }

    /**
     * Resolve the php-scoper binary: prefer the monorepo vendor/bin, then PATH.
     */
    public function locateScoper(): ?string
    {
        foreach ([__DIR__ . '/../../../../vendor/bin/php-scoper', __DIR__ . '/../../vendor/bin/php-scoper'] as $candidate) {
            if (is_file($candidate)) {
                return $candidate;
            }
        }

        return $this->runner->which('php-scoper');
    }
}
